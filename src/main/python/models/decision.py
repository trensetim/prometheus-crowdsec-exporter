import re
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any, Type

from models._base import (
    boolField,
    datetimeField,
    intField,
    requiredFieldsPresent,
    strField,
)

@dataclass(frozen=True)
# pylint: disable=too-many-instance-attributes
class Decision:
    """Information about a single CrowdSec decision, as returned by the CrowdSec LAPI /v1/decisions endpoint."""

    decision_id: int
    """simple counter that CrowdSec LAPI increments for each new decision it makes on it's own."""
    decision_uuid: str
    """unique identifier for the decision, generated by CrowdSec LAPI."""
    type: str
    origin: str
    scenario: str
    scope: str
    value: str
    duration: str
    until: datetime | None
    simulated: bool

    @classmethod
    def parse(cls: Type["Decision"], raw: dict[str, Any], created_at_hint: datetime) -> "Decision | None":
        if not isinstance(raw, dict):
            raise ValueError("Decision is not a dict")

        missing = requiredFieldsPresent(raw, ["type", "origin", "scenario", "scope"])
        if missing:
            raise ValueError(f"Decision is missing required fields: {missing}")

        duration = strField(raw, "duration", fallback="")
        until = datetimeField(raw, "until")
        if until is None:
            until = created_at_hint + cls._parse_duration(duration)

        return cls(
            decision_id = intField(raw, "id"),
            decision_uuid = strField(raw, "uuid", fallback=""),
            type = strField(raw, "type"),
            origin = strField(raw, "origin"),
            scenario = strField(raw, "scenario"),
            scope = strField(raw, "scope"),
            value = strField(raw, "value", fallback=""),
            duration = duration,
            until = until,
            simulated = boolField(raw, "simulated"),
        )

    def parse_duration(self) -> timedelta:
        return Decision._parse_duration(self.duration)

    @staticmethod
    def _parse_duration(duration: str) -> timedelta:
        # duration is eg. "7d24h60m20s" or ""
        pattern = re.compile(r"(?:(\d+)d)?(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?")
        match = pattern.fullmatch(duration)
        if not match:
            return timedelta(seconds=0)
        days, hours, minutes, seconds = match.groups(default="0")
        days, hours, minutes, seconds = (int(days), int(hours), int(minutes), int(seconds))
        return timedelta(days=days, hours=hours, minutes=minutes, seconds=seconds)

    @staticmethod
    def metric_labels() -> list[str]:
        return [
            "alert_id",
            "alert_uuid",
            "decision_id",
            "decision_uuid",
            "type",
            "origin",
            "scenario",
            "scope",
            "value",
            "duration",
            "until",
            "simulated",
        ]

    def metric_label_values(self, alert_id: int, alert_uuid: str) -> list[str]:
        return [
            str(alert_id),
            alert_uuid,
            str(self.decision_id),
            self.decision_uuid,
            self.type,
            self.origin,
            self.scenario,
            self.scope,
            self.value,
            self.duration,
            self.until.isoformat() if self.until else "",
            str(self.simulated).lower(),
        ]
